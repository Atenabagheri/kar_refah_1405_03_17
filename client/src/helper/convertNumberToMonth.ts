export const convertNumberToMonth = (monthNumber: number) => {
  if (!monthNumber) return;
  const month = [
    "فروردین",
    "اردیبهشت",
    "خرداد",
    "تیر",
    "مرداد",
    "شهریور",
    "مهر",
    "آبان",
    "آذر",
    "دی",
    "بهمن",
    "اسفند",
  ];
  return month[monthNumber - 1];
};
